"""Fuente unica de los casos de uso (12-casos-de-uso.md y sus diagramas).

Cada caso de uso sale de los requerimientos de `11-analisis-requerimientos.md`
y dice cuales cubre. `_verificar_uml.py` comprueba que los 44 requerimientos
funcionales esten cubiertos por al menos un caso de uso, que cada caso de
uso se dibuje como propio en exactamente un diagrama, y que no se cite un
requerimiento o una ventana que no exista.

MODESEC pide que los casos de uso cumplan dos objetivos: *"Definir los
requisitos funcionales del sistema y proporcionar una base para la
validacion de las pruebas"*. Por eso cada uno trae, ademas del flujo, una
PRUEBA DE ACEPTACION: un caso concreto que, al construir el incremento,
dice si el caso de uso quedo bien hecho.
"""


